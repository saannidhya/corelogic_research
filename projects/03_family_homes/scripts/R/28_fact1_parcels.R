#' Rates per 100 parcels a year for one region (sums over its states)
#' @param d State-year rows.
#' @param region_label Label.
#' @return Tibble by year plus the pooled 2007-2023 row (year NA).
region_rates <- function(d, region_label) {
  by_year <- d %>%
    group_by(year) %>%
    summarise(across(c(deeds_main, deeds_upper, deeds_market, deeds_all, deeds_resid_main,
                       deeds_resid_upper, deeds_resid_market, parcels_with_deed_main,
                       parcels_dynamic, parcels_static, panel_parcels), ~ sum(.x, na.rm = TRUE)),
              .groups = "drop")
  pooled <- by_year %>% summarise(across(-year, sum)) %>% mutate(year = NA_integer_)
  bind_rows(by_year, pooled) %>%
    mutate(region = region_label,
           # headline: deeds on universe parcels per 100 universe parcels standing that year
           main_per100 = 100 * deeds_resid_main / parcels_dynamic,
           upper_per100 = 100 * deeds_resid_upper / parcels_dynamic,
           market_per100 = 100 * deeds_resid_market / parcels_dynamic,
           main_parcels_per100 = 100 * parcels_with_deed_main / parcels_dynamic,
           # sensitivity: static parcel count
           main_per100_static = 100 * deeds_resid_main / parcels_static,
           market_per100_static = 100 * deeds_resid_market / parcels_static,
           # bound: all deeds over parcels that ever had a deed, 2007-2024
           main_per100_panel = 100 * deeds_main / panel_parcels,
           upper_per100_panel = 100 * deeds_upper / panel_parcels,
           market_per100_panel = 100 * deeds_market / panel_parcels,
           # the paper's Fact 1 basis, for reference: per 100 deed events
           main_per100_deeds = 100 * deeds_main / deeds_all,
           family_to_market = deeds_resid_main / deeds_resid_market,
           upper_to_market = deeds_resid_upper / deeds_resid_market) %>%
    relocate(region, year)
}


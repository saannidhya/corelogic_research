# Purpose : Fact 1 per home (simulated JUE review, item A5; plan 2026-11-12_review-
#           analyses.md, WP R3): family transfers per 100 residential parcels per year,
#           nationally and for California, 2007-2023 average and by year, beside market
#           turnover (market sales per 100 parcels per year), on the paper's family
#           predicate (the main family measure of Table 2) and on its upper bound (the
#           main measure plus same-person and entity deeds).
#
#           Parcel universe (headline): CoreLogic property-characteristics parcels, read
#           through shared_utils/R/corelogic_loader.R, with property indicator 10
#           (single-family), 11 (condominium) or 21 (duplex to fourplex): the codes the
#           deed file's residential flag accepts. The property file covers 44 states and
#           DC (none for CT, NH, RI; essentially empty for MA, ME, SD) and does not hold
#           every parcel that has deeds, so the numerator counts only deeds on parcels in
#           the universe, state by state; the rate is deeds on universe parcels over
#           universe parcels. Parcels count in a year if built by that year or with no
#           year built recorded (static count as a sensitivity). The property file is a
#           snapshot of tax year 2008 (checked below), so the universe is the residential
#           parcel stock of about 2008: later parcels and their deeds are outside it, and
#           the year-built adjustment barely moves the count.
#           Second universe (bound): every parcel with at least one residential deed event
#           in the panel, 2007-2024. It leaves out parcels that never traded, so its rates
#           are upper bounds per parcel.
# Name    : Saani Rawat
# Created : 11/13/2026
# Log     : 11/13/2026: created (WP R3).
# Inputs  : data/corelogic_extracts/by_state/prop (via register_corelogic_parquet());
#           data/derived/03_family_homes/events.parquet (events_main_from());
#           _outputs/section23/s23_totals_state_year.csv, s23_cells_state_year.csv (check)
# Outputs : _outputs/tables/r3_fact1_parcel_universe.csv, r3_fact1_state_year.csv,
#           r3_fact1_by_year.csv, r3_fact1_summary.csv, r3_macros_28.csv;
#           rebuilds r3_numbers.tex and r3_number_sources.csv
#======================================================================#


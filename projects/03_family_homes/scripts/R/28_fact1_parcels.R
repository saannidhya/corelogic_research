# one state at a time: property columns are numeric in some partitions and text in others
prop_states <- sub("state=", "", path_file(dir_ls(path(default_parquet_root(), "by_state", "prop"),
                                                    type = "directory")))
prop_states <- intersect(prop_states, states_51)
dbExecute(con, "CREATE OR REPLACE TEMP TABLE pc (clip BIGINT, state VARCHAR, ind VARCHAR, yb INTEGER, tax_year INTEGER)")
for (st in prop_states) {
  register_corelogic_parquet(con, "prop", states = st, view_name = "prop_src")
  invisible(dbExecute(con, glue("
    INSERT INTO pc
    SELECT TRY_CAST(clip AS BIGINT), '{st}',
           NULLIF(regexp_replace(trim(CAST(property_indicator_code AS VARCHAR)), '\\.0$', ''), ''),
           TRY_CAST(year_built AS INTEGER), TRY_CAST(tax_year AS INTEGER)
    FROM prop_src WHERE TRY_CAST(clip AS BIGINT) IS NOT NULL")))
}
invisible(dbExecute(con, "DROP VIEW IF EXISTS prop_src"))

# vintage of the property file: modal tax year and the 99th percentile of year built by state
# (the file is a snapshot, so parcels created after it are outside the universe)
pc_vintage <- dbGetQuery(con, "
  SELECT state, mode(tax_year) AS tax_year_mode,
         approx_quantile(CASE WHEN yb BETWEEN 1600 AND 2030 THEN yb END, 0.99) AS yb_p99,
         SUM(CASE WHEN yb BETWEEN 2010 AND 2030 THEN 1 ELSE 0 END) AS n_built_2010_on
  FROM pc GROUP BY state") %>% as_tibble()
message("Property-file tax year (mode across states): ",
        paste(names(table(pc_vintage$tax_year_mode)), table(pc_vintage$tax_year_mode), sep = ": ", collapse = "; "),
        "; parcels built 2010 or later: ", format(sum(pc_vintage$n_built_2010_on), big.mark = ","))
pc_dupes <- dbGetQuery(con, "SELECT COUNT(*) - COUNT(DISTINCT (state, clip)) AS n_dup FROM pc")$n_dup
message("Property parcels loaded: ", format(dbGetQuery(con, "SELECT COUNT(*) n FROM pc")$n, big.mark = ","),
        "; duplicate state-parcel keys: ", pc_dupes)
stopifnot(pc_dupes == 0)

# one row per state-parcel with the universe flag; year built 0 or missing counts every year
dbExecute(con, glue("
  CREATE OR REPLACE TEMP TABLE pc_u AS
  SELECT state, clip,
         CASE WHEN ind IN ('{paste(resid_codes, collapse = \"','\")}') THEN 1 ELSE 0 END AS resid,
         CASE WHEN yb BETWEEN 1600 AND 2030 THEN yb ELSE NULL END AS yb
  FROM pc"))
dbExecute(con, "DROP TABLE pc")

parcel_counts <- dbGetQuery(con, "
  SELECT state, resid, coalesce(yb, 0) AS yb, COUNT(*) AS n
  FROM pc_u GROUP BY ALL") %>% as_tibble() %>% mutate(n = as.numeric(n))

#============================================#
# Importing deeds and matching them to parcels ----
#============================================#

ev <- events_main_from(events_panel_path)   # family measure of 2026-11-12 (00_setup.R)
meas_sql <- glue("
  CASE WHEN class IN {family_classes_sql} THEN 'main'
       WHEN class = '{family_samep_label}' THEN 'samep_entity'
       WHEN class = 'market_sale' THEN 'market'
       ELSE 'other' END")
dbExecute(con, glue("
  CREATE OR REPLACE TEMP TABLE dd AS
  SELECT clip, state, sale_year, {meas_sql} AS meas
  FROM {ev}
  WHERE sale_year BETWEEN 2007 AND 2024 AND clip IS NOT NULL"))

# deeds by state, year and measure: all deeds, on any property parcel, on universe parcels;
# distinct universe parcels with a deed of the measure in the year
deed_counts <- dbGetQuery(con, glue("
  SELECT d.state, d.sale_year, d.meas,
         COUNT(*) AS deeds,
         SUM(CASE WHEN p.clip IS NOT NULL THEN 1 ELSE 0 END) AS deeds_pc_any,
         SUM(CASE WHEN p.resid = 1 THEN 1 ELSE 0 END) AS deeds_resid,
         COUNT(DISTINCT CASE WHEN p.resid = 1 THEN d.clip END) AS parcels_resid_with_deed
  FROM dd d LEFT JOIN pc_u p ON d.state = p.state AND d.clip = p.clip
  WHERE d.sale_year BETWEEN {min(years)} AND {max(years)}
  GROUP BY ALL")) %>% as_tibble() %>%
  mutate(across(c(deeds, deeds_pc_any, deeds_resid, parcels_resid_with_deed), as.numeric))

# second universe: every parcel with a residential deed event in the panel, 2007-2024
